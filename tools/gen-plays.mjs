// Writes the generated native play scripts (tests/native/*.play) from the rules:
// each puzzle's pieces in tray order, rotated upright (R) and placed on their home
// cell, through the accessible mirror (the tray-piece and board-cell buttons),
// the board cursor (digit keys, arrows, Enter) or the Hint button — the same
// moves a player makes, so the scripts reach the results deterministically.
//   node tools/gen-plays.mjs        (menus.play is written by hand)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as R from '../rules.js';
import { LESSONS, JOURNEY, CHALLENGES } from '../content.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (name, lines) => { writeFileSync(join(root, 'tests/native', name), lines.join('\n') + '\n'); console.log('wrote tests/native/' + name); };

const cellName = (rs, c) => `Cell column ${c % rs.cols + 1} row ${Math.floor(c / rs.cols) + 1},`;
/** Mirror play: click a piece, rotate it upright with R, click its home cell. */
function mirrorSolve(seed, rs, press = 'click') {
  const s = R.newGame(seed, rs);
  const lines = [];
  for (const id of s.tray) {
    const p = s.pieces[id];
    lines.push('frames 5', `${press} Piece ${id + 1},`, 'frames 8');
    for (let k = 0; k < (4 - p.rot) % 4; k++) lines.push('key KeyR 1', 'frames 5');
    lines.push(`${press} ${cellName(s.ruleset, p.cell)}`, 'frames 8');
  }
  return lines;
}
/** Keyboard play: pick the first open tray piece (1), walk the board cursor to its home cell, Enter. */
function cursorSolve(seed, rs, skip = 0) {
  const s = R.newGame(seed, rs);
  const lines = [];
  let cursor = -1;
  for (const id of s.tray.slice(skip)) {
    const p = s.pieces[id];
    lines.push('frames 5', 'key Digit1 1', 'frames 8');
    for (let k = 0; k < (4 - p.rot) % 4; k++) lines.push('key KeyR 1', 'frames 5');
    if (cursor < 0) { lines.push('key ArrowRight 1', 'frames 5'); cursor = 0; } // the first arrow shows the cursor on cell 1
    const dx = p.cell % rs.cols - cursor % rs.cols, dy = Math.floor(p.cell / rs.cols) - Math.floor(cursor / rs.cols);
    for (let k = 0; k < Math.abs(dx); k++) lines.push(`key ${dx > 0 ? 'ArrowRight' : 'ArrowLeft'} 1`, 'frames 4');
    for (let k = 0; k < Math.abs(dy); k++) lines.push(`key ${dy > 0 ? 'ArrowDown' : 'ArrowUp'} 1`, 'frames 4');
    cursor = p.cell;
    lines.push('key Enter 1', 'frames 8');
  }
  return lines;
}

